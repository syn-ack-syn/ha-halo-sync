export const STRINGS = { en, de };

/** "de" for every language code starting with "de", otherwise "en". */
export function pickLang(lang) {
  return String(lang || "").toLowerCase().startsWith("de") ? "de" : "en";
}

/**
 * t(key, vars) for the language: "{name}" placeholders are filled from vars, a missing key falls back
 * to English, then to the key itself. t.has(key) tells whether a text exists, t.lang is "en" or "de".
 */
export function makeT(lang) {
  const l = pickLang(lang);
  const table = STRINGS[l];
  const t = (key, vars) => {
    const s = table[key] ?? STRINGS.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k]))) : s;
  };
  t.has = (key) => key in table || key in STRINGS.en;
  t.lang = l;
  return t;
}
